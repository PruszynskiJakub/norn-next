function defaultCell(key: string): string {
  if (!(key in KEY_DEFAULTS)) return "none";
  const v = KEY_DEFAULTS[key];
  if (typeof v === "object" && v !== null && "derived" in v) return tableCell(`derived: ${(v as { derived: string }).derived}`);
  return `\`${tableCell(JSON.stringify(v))}\``;
}

/** The config keys as rows, and the maps that take their plugin's keys beside norn's. */
export function configKeys(): { rows: ConfigRow[]; open: string[] } {
  const open: string[] = [];
  const rows = configRows(ConfigLayer as unknown as Schema, [], open);
  return { rows, open };
}

