/** `name:` and `description:` of a shipped workflow file. */
function workflowLine(text: string): string {
  const doc = parse(text) as { name?: unknown; description?: unknown };
  const description = typeof doc.description === "string" ? doc.description.trim().replace(/\s+/g, " ") : "";
  return `- \`${String(doc.name ?? "?")}\`: ${description}`;
}

/** What each exit code means; a code with no line here fails the reference test. */
export const EXIT_MEANING: Record<keyof typeof ExitCode, string> = {
  ok: "done",
  error: "an unexpected failure: a bug or an IO error",
  usage: "bad arguments",
  refused: "a rule says no; `do_instead` says what would succeed",
  corrupt: "a file norn keeps failed validation",
  busy: "another process holds the lock or the claim",
  config: "a config file a person wrote needs fixing",
};

export interface ReferenceInput {
  commands: readonly Command[];
  nouns: readonly Noun[];
  /** the name of the pack whose workflows are listed */
  pack: string;
  /** the text of each workflow file that pack ships */
  workflows: readonly string[];
}

/** The generated block, markers included. */
export function renderReference(input: ReferenceInput): string {
  const out = [REFERENCE_START, "", "### Commands", "", "Every command also takes `--json` (one JSON value instead of markdown) and `--help`.", ""];
  for (const tier of commandOrder(input.commands, input.nouns)) {
    out.push(`#### ${tier.title}`, "");
    for (const item of tier.items) {
      if ("verbs" in item) {
        out.push(`##### \`norn ${item.name}\` (noun)`, "", item.summary, "");
        for (const v of item.verbs) out.push(...renderCommand(v));
      } else out.push(...renderCommand(item));
    }
  }
  out.push("### Config keys", "", ...renderConfig(), "");
  out.push("### Shipped workflows", "", `The \`${input.pack}\` pack's workflows, each drawn as a graph in [Workflows](workflows.md):`, "", ...input.workflows.map(workflowLine).sort(), "");
  out.push(
    "### Exit codes",
    "",
    "| Code | Name | Meaning |",
    "|---|---|---|",
    ...(Object.entries(ExitCode) as Array<[keyof typeof ExitCode, number]>).map(([k, v]) => `| ${v} | \`${k}\` | ${tableCell(EXIT_MEANING[k])} |`),
    "",
  );
  out.push(REFERENCE_END);
  return out.join("\n");
}

/** `doc` with the text between `markers` replaced by `block`; prose around them is kept. */
export function replaceReference(doc: string, block: string, markers: MarkerPair): string {
  const start = doc.indexOf(markers.start);
  const end = doc.indexOf(markers.end);
  if (start < 0 || end < start) throw new Error(`no generated block: add the two marker comments ${markers.start} and ${markers.end}`);
  return doc.slice(0, start) + block + doc.slice(end + markers.end.length);
}

/** The generated block between `markers` in `doc`, markers included, or undefined. */
export function currentReference(doc: string, markers: MarkerPair): string | undefined {
  const start = doc.indexOf(markers.start);
  const end = doc.indexOf(markers.end);
  return start < 0 || end < start ? undefined : doc.slice(start, end + markers.end.length);
}
