export const REFERENCE_FILE = "docs/reference.md";
export const REFERENCE_START = "<!-- norn:reference:start — generated by `bun run docs:emit`; edit the cli, not this block -->";
export const REFERENCE_END = "<!-- norn:reference:end -->";

/** The two marker comments a generated block sits between in a doc; the prose outside them is a person's. */
export interface MarkerPair {
  start: string;
  end: string;
}
export const REFERENCE_MARKERS: MarkerPair = { start: REFERENCE_START, end: REFERENCE_END };

/**
 * Who runs what, the order a reader looks for it in. A command in no group lands under Other, so a new
 * command is listed before anyone files it.
 */
export const REFERENCE_GROUPS: ReadonlyArray<{ title: string; commands: readonly string[] }> = [
  { title: "Setup", commands: ["init", "doctor", "config", "plugin"] },
  { title: "A person's commands", commands: ["status", "story", "run", "workflow"] },
  { title: "Background: run by a person, cron or a terminal multiplexer", commands: ["watch", "tick"] },
  { title: "Agent protocol: the only commands an agent runs", commands: ["brief", "done", "ask", "stuck"] },
  { title: "Called by the harness's hooks, not by hand", commands: ["hook"] },
];

function commandOrder(commands: readonly Command[], nouns: readonly Noun[]): Array<{ title: string; items: Array<Command | Noun> }> {
  const find = (name: string): Command | Noun | undefined => nouns.find((n) => n.name === name) ?? commands.find((c) => c.name === name);
  const grouped = new Set(REFERENCE_GROUPS.flatMap((g) => g.commands));
  const tiers = REFERENCE_GROUPS.map((g) => ({ title: g.title, items: g.commands.flatMap((n) => find(n) ?? []) }));
  const other = { title: "Other", items: [...commands, ...nouns].filter((c) => !grouped.has(c.name)) };
  return [...tiers, other].filter((t) => t.items.length > 0);
}

function renderCommand(c: Command): string[] {
  const help = c.optionHelp ?? {};
  const named = new Set(Object.keys(help).flatMap((k) => [...k.matchAll(/--([\w-]+)/g)].map((m) => m[1])));
  const options = [
    ...Object.entries(help).map(([k, v]) => `- \`${k}\`: ${v}`),
    ...Object.keys(c.options ?? {})
      .filter((k) => !named.has(k))
      .map((k) => `- \`--${k}\``),
  ];
  const personOnly = typeof c.personOnly === "object" ? [c.personOnly.help, ""] : c.personOnly ? ["A person's command: refused in an agent's session (`person_only`).", ""] : [];
  return [`##### \`norn ${c.name}\``, "", c.summary, "", ...personOnly, "```sh", c.usage, "```", "", ...(options.length ? [...options, ""] : [])];
}

type Schema = Record<string, unknown>;
interface ConfigRow {
  key: string;
  type: string;
}

const props = (s: Schema): Record<string, Schema> | undefined => s.properties as Record<string, Schema> | undefined;
const patternProps = (s: Schema): Schema | undefined => Object.values((s.patternProperties as Record<string, Schema> | undefined) ?? {})[0];

/** A schema's type in words, read off the schema itself. */
function typeName(s: Schema): string {
  if (Array.isArray(s.anyOf)) {
    const branches = s.anyOf as Schema[];
    // a long closed list is named by its title, and spelled out where the title is explained
    if (branches.every((b) => "const" in b) && typeof s.title === "string") return s.title;
    if (branches.every((b) => "const" in b)) return branches.map((b) => `\`${JSON.stringify(b.const)}\``).join(" or ");
    return branches.map(typeName).join(" or ");
  }
  if ("const" in s) return `\`${JSON.stringify(s.const)}\``;
  if (s.type === "null") return "null";
  if (s.type === "boolean") return "boolean";
  if (s.type === "string") return typeof s.pattern === "string" && s.pattern.includes("(ms|s|m|h|d)") ? "duration" : "string";
  if (s.type === "integer") return typeof s.minimum === "number" ? `integer ≥ ${s.minimum}` : "integer";
  if (s.type === "array") {
    const items = s.items as Schema;
    const one = typeof s.maxItems === "number" && s.maxItems === 1 ? " (one)" : "";
    const item = typeName(items);
    return `list of ${item.endsWith("y") ? `${item.slice(0, -1)}ies` : `${item}s`}${one}`;
  }
  if (s.type === "object") return "map";
  return "any";
}

/** Keys that open a map: a record's keys are names a person picks, shown as a placeholder. */
const RECORD_KEY: Record<string, string> = { executors: "<name>", plugins: "<name>", checks: "<name>", sources: "<name>", bind: "<role>" };

/**
 * Every key a config file can hold, walked from the file's schema: a map's own keys nest
 * (`tracker.intake.label`), a record's take a placeholder (`executors.<name>.harness`), and a
 * map-or-name both nests and has a row of its own. `open` collects the maps that also take their
 * plugin's own keys.
 */
function configRows(s: Schema, path: string[], open: string[]): ConfigRow[] {
  const key = path.join(".");
  const here: ConfigRow = { key, type: typeName(s) };
  const record = patternProps(s);
  if (record) return configRows(record, [...path, RECORD_KEY[key] ?? "<key>"], open);
  const object = Array.isArray(s.anyOf) ? (s.anyOf as Schema[]).find((b) => props(b)) : s;
  const fields = object && props(object);
  if (!fields) return [here];
  if (object.additionalProperties === true) open.push(key);
  const own = Object.entries(fields).flatMap(([k, child]) => configRows(child, [...path, k], open));
  return path.length && object !== s ? [here, ...own] : own;
}

const UNITS: ReadonlyArray<[string, number]> = [
  ["d", 86_400_000],
  ["h", 3_600_000],
  ["m", 60_000],
  ["s", 1_000],
  ["ms", 1],
];

/** 900000 → `15m`: the largest unit that divides it, as a config file spells it. */
export function durationText(ms: number): string {
  const [unit, size] = UNITS.find(([, n]) => ms % n === 0) ?? ["ms", 1];
  return `${ms / size}${unit}`;
}

