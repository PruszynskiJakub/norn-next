/**
 * The generated part of docs/reference.md: every command and verb with its usage and options, every
 * config key with the files that take it, its type (read off the file schemas) and built-in default, the shipped workflows and the exit
 * codes, rendered from the cli's own registry, the built-in config and the shipped assets. Pure: the
 * caller passes the workflow files' text. `bun run docs:emit` writes it between the markers; a unit
 * test fails when the file is stale.
 */
import { CONFIG_SCHEMAS, type ConfigFileKind, DEFAULT_CONFIG, Duration, ExitCode, Url } from "@norn/schema";
import type { Command, Noun } from "./command.ts";
import { HELP_GROUPS, plainSummary } from "./commands/help.ts";
import { tableCell } from "./output.ts";

export const REFERENCE_FILE = "docs/reference.md";
export const REFERENCE_START = "<!-- norn:reference:start — generated by `bun run docs:emit`; edit the cli, not this block -->";
export const REFERENCE_END = "<!-- norn:reference:end -->";

/** `help` is the footer of `norn help`, not a row; it is listed under Other here. */
function commandOrder(commands: readonly Command[], nouns: readonly Noun[]): Array<{ title: string; items: Array<Command | Noun> }> {
  const find = (name: string): Command | Noun | undefined => nouns.find((n) => n.name === name) ?? commands.find((c) => c.name === name);
  const grouped = new Set(HELP_GROUPS.flatMap((g) => g.commands));
  const tiers = HELP_GROUPS.map((g) => ({ title: g.title, items: g.commands.flatMap((n) => find(n) ?? []) }));
  const other = { title: "Other", items: [...commands, ...nouns].filter((c) => !grouped.has(c.name)) };
  return [...tiers, other].filter((t) => t.items.length > 0);
}

function renderCommand(c: Command): string[] {
  const help = c.optionHelp ?? {};
  const named = new Set(Object.keys(help).flatMap((k) => [...k.matchAll(/--([\w-]+)/g)].map((m) => m[1])));
  const options = [
    ...Object.entries(help).map(([k, v]) => `- \`${k}\`: ${v}`),
    ...Object.keys(c.options ?? {})
      .filter((k) => !named.has(k))
      .map((k) => `- \`--${k}\``),
  ];
  return [`##### \`norn ${c.name}\``, "", plainSummary(c.summary), "", "```sh", c.usage, "```", "", ...(options.length ? [...options, ""] : [])];
}

type Schema = Record<string, unknown>;
interface ConfigRow {
  key: string;
  type: string;
  /** the built-in default at this key; undefined when there is none */
  value: unknown;
}

const props = (s: Schema): Record<string, Schema> | undefined => s.properties as Record<string, Schema> | undefined;

/** A schema's type in words, read off the schema itself, never off a default value. */
function typeName(s: Schema): string {
  if (Array.isArray(s.anyOf)) {
    const branches = s.anyOf as Schema[];
    if (branches.every((b) => "const" in b)) return branches.map((b) => `\`${JSON.stringify(b.const)}\``).join(" or ");
    return branches.map(typeName).join(" or ");
  }
  if (s.type === "null") return "null";
  if (s.type === "boolean") return "boolean";
  if (s.type === "string" && s.pattern === Url.pattern) return "URL";
  // trace.retain is a plain string checked where it is used, but holds a duration all the same
  if (s.type === "string") return s.pattern === Duration.pattern || String(s.description).startsWith("Duration") ? "duration" : "string";
  if (s.type === "integer") {
    if (typeof s.minimum === "number" && typeof s.maximum === "number") return `integer ${s.minimum}–${s.maximum}`;
    return typeof s.minimum === "number" ? `integer ≥ ${s.minimum}` : "integer";
  }
  if (s.type === "array") return `list of ${typeName(s.items as Schema)}s`;
  if (s.type === "object") return "map";
  return "any";
}

/**
 * Every key a config file can hold, walked from the file's schema: a map's own keys nest
 * (`notify.ntfy`, `agents.claude.model`), and a map-or-null both nests and has a row of its own.
 */
function configRows(s: Schema, path: string[], defaults: unknown): ConfigRow[] {
  const key = path.join(".");
  const here: ConfigRow = { key, type: typeName(s), value: defaults };
  const object = Array.isArray(s.anyOf) ? (s.anyOf as Schema[]).find((b) => props(b)) : s;
  const fields = object && props(object);
  if (!fields) return [here];
  const own = Object.entries(fields)
    .filter(([k]) => k !== "$schema")
    .flatMap(([k, child]) => configRows(child, [...path, k], at(defaults, k)));
  return path.length && object !== s ? [here, ...own] : own;
}

const at = (v: unknown, k: string): unknown => (typeof v === "object" && v !== null && !Array.isArray(v) ? (v as Record<string, unknown>)[k] : undefined);

/** How the table names each file: `~/.norn/config.yaml`, the local file, the team file. */
export const FILE_LABEL: Record<ConfigFileKind, string> = { user: "user", local: "local", repo: "team" };

/** Keys whose value, when no file sets it, is derived from the repo, not a fixed built-in default. */
const DERIVED_DEFAULT: Record<string, string> = {
  provider: "derived from the remote URL",
  base_branch: "derived: the remote's default branch",
};

function defaultCell(r: ConfigRow): string {
  const derived = DERIVED_DEFAULT[r.key];
  if (derived) return tableCell(derived);
  return r.value === undefined ? "none" : `\`${tableCell(JSON.stringify(r.value))}\``;
}

function renderConfig(): string[] {
  const rows = new Map<string, ConfigRow & { files: string[] }>();
  for (const [kind, schema] of Object.entries(CONFIG_SCHEMAS) as Array<[ConfigFileKind, unknown]>) {
    for (const r of configRows(schema as Schema, [], DEFAULT_CONFIG)) {
      const row = rows.get(r.key) ?? { ...r, files: [] };
      row.files.push(FILE_LABEL[kind]);
      rows.set(r.key, row);
    }
  }
  return [
    "| Key | File | Type | Built-in default |",
    "|---|---|---|---|",
    ...[...rows.values()].map((r) => `| \`${r.key}\` | ${r.files.join(", ")} | ${tableCell(r.type)} | ${defaultCell(r)} |`),
  ];
}

/** `name:` and `description:` of a shipped workflow file, read as text. */
function workflowLine(text: string): string {
  const name = /^name:\s*(.+)$/m.exec(text)?.[1]?.trim() ?? "?";
  const description = /^description:\s*(.+)$/m.exec(text)?.[1]?.trim() ?? "";
  return `- \`${name}\`: ${description}`;
}

export interface ReferenceInput {
  commands: readonly Command[];
  nouns: readonly Noun[];
  /** the text of each workflow file `norn init` ships */
  workflows: readonly string[];
}

/** The generated block, markers included. */
export function renderReference(input: ReferenceInput): string {
  const out = [REFERENCE_START, "", "### Commands", ""];
  for (const tier of commandOrder(input.commands, input.nouns)) {
    out.push(`#### ${tier.title}`, "");
    for (const item of tier.items) {
      if ("verbs" in item) {
        out.push(`##### \`norn ${item.name}\` (noun)`, "", plainSummary(item.summary), "");
        for (const v of item.verbs) out.push(...renderCommand(v));
      } else out.push(...renderCommand(item));
    }
  }
  out.push("### Config keys", "", ...renderConfig(), "");
  out.push("### Shipped workflows", "", ...input.workflows.map(workflowLine).sort(), "");
  out.push("### Exit codes", "", "| Code | Name |", "|---|---|", ...Object.entries(ExitCode).map(([k, v]) => `| ${v} | \`${k}\` |`), "");
  out.push(REFERENCE_END);
  return out.join("\n");
}

/** `doc` with the text between the markers replaced by `block`; prose around them is kept. */
export function replaceReference(doc: string, block: string): string {
  const start = doc.indexOf(REFERENCE_START);
  const end = doc.indexOf(REFERENCE_END);
  if (start < 0 || end < start) throw new Error(`${REFERENCE_FILE} has no generated block: add the two marker comments`);
  return doc.slice(0, start) + block + doc.slice(end + REFERENCE_END.length);
}

/** The generated block currently in `doc`, markers included, or undefined. */
export function currentReference(doc: string): string | undefined {
  const start = doc.indexOf(REFERENCE_START);
  const end = doc.indexOf(REFERENCE_END);
  return start < 0 || end < start ? undefined : doc.slice(start, end + REFERENCE_END.length);
}
