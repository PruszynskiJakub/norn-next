/**
 * The generated part of docs/reference.md (gh-162 B8–B13): every command and verb with its usage and
 * options, every config key with its type and built-in default, the shipped workflows and the exit
 * codes, rendered from the cli's own registry, the built-in config and the shipped assets. Pure: the
 * caller passes the workflow files' text. `bun run docs:emit` writes it between the markers; a unit
 * test fails when the file is stale.
 */
import { type ConfigEntry, ExitCode, explainConfig } from "@norn/schema";
import type { Command, Noun } from "./command.ts";
import { HELP_GROUPS, plainSummary } from "./commands/help.ts";

export const REFERENCE_FILE = "docs/reference.md";
export const REFERENCE_START = "<!-- norn:reference:start — generated by `bun run docs:emit`; edit the cli, not this block -->";
export const REFERENCE_END = "<!-- norn:reference:end -->";

/** `help` is the footer of `norn help`, not a row; it is listed under Other here. */
function commandOrder(commands: readonly Command[], nouns: readonly Noun[]): Array<{ title: string; items: Array<Command | Noun> }> {
  const find = (name: string): Command | Noun | undefined => nouns.find((n) => n.name === name) ?? commands.find((c) => c.name === name);
  const grouped = new Set(HELP_GROUPS.flatMap((g) => g.commands));
  const tiers = HELP_GROUPS.map((g) => ({ title: g.title, items: g.commands.flatMap((n) => find(n) ?? []) }));
  const other = { title: "Other", items: [...commands, ...nouns].filter((c) => !grouped.has(c.name)) };
  return [...tiers, other].filter((t) => t.items.length > 0);
}

function renderCommand(c: Command): string[] {
  const help = c.optionHelp ?? {};
  const named = new Set(Object.keys(help).flatMap((k) => [...k.matchAll(/--([\w-]+)/g)].map((m) => m[1])));
  const options = [
    ...Object.entries(help).map(([k, v]) => `- \`${k}\`: ${v}`),
    ...Object.keys(c.options ?? {})
      .filter((k) => !named.has(k))
      .map((k) => `- \`--${k}\``),
  ];
  return [`##### \`norn ${c.name}\``, "", plainSummary(c.summary), "", "```sh", c.usage, "```", "", ...(options.length ? [...options, ""] : [])];
}

const typeOf = (v: unknown): string => (Array.isArray(v) ? "list" : v === null ? "null" : typeof v === "object" ? "map" : typeof v);
const cell = (s: string): string => s.replace(/\|/g, "\\|");

function renderConfig(entries: readonly ConfigEntry[]): string[] {
  return [
    "| Key | Type | Built-in default |",
    "|---|---|---|",
    ...entries.map((e) => `| \`${e.key}\` | ${typeOf(e.value)} | \`${cell(JSON.stringify(e.value))}\` |`),
  ];
}

/** `name:` and `description:` of a shipped workflow file, read as text. */
function workflowLine(text: string): string {
  const name = /^name:\s*(.+)$/m.exec(text)?.[1]?.trim() ?? "?";
  const description = /^description:\s*(.+)$/m.exec(text)?.[1]?.trim() ?? "";
  return `- \`${name}\`: ${description}`;
}

export interface ReferenceInput {
  commands: readonly Command[];
  nouns: readonly Noun[];
  /** the text of each workflow file `norn init` ships */
  workflows: readonly string[];
}

/** The generated block, markers included. */
export function renderReference(input: ReferenceInput): string {
  const out = [REFERENCE_START, "", "### Commands", ""];
  for (const tier of commandOrder(input.commands, input.nouns)) {
    out.push(`#### ${tier.title}`, "");
    for (const item of tier.items) {
      if ("verbs" in item) {
        out.push(`##### \`norn ${item.name}\` (noun)`, "", plainSummary(item.summary), "");
        for (const v of item.verbs) out.push(...renderCommand(v));
      } else out.push(...renderCommand(item));
    }
  }
  out.push("### Config keys", "", ...renderConfig(explainConfig()), "");
  out.push("### Shipped workflows", "", ...input.workflows.map(workflowLine).sort(), "");
  out.push("### Exit codes", "", "| Code | Name |", "|---|---|", ...Object.entries(ExitCode).map(([k, v]) => `| ${v} | \`${k}\` |`), "");
  out.push(REFERENCE_END);
  return out.join("\n");
}

/** `doc` with the text between the markers replaced by `block`; prose around them is kept (B12). */
export function replaceReference(doc: string, block: string): string {
  const start = doc.indexOf(REFERENCE_START);
  const end = doc.indexOf(REFERENCE_END);
  if (start < 0 || end < start) throw new Error(`${REFERENCE_FILE} has no generated block: add the two marker comments`);
  return doc.slice(0, start) + block + doc.slice(end + REFERENCE_END.length);
}

/** The generated block currently in `doc`, markers included, or undefined. */
export function currentReference(doc: string): string | undefined {
  const start = doc.indexOf(REFERENCE_START);
  const end = doc.indexOf(REFERENCE_END);
  return start < 0 || end < start ? undefined : doc.slice(start, end + REFERENCE_END.length);
}
