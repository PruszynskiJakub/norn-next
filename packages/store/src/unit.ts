/**
 * One unit's `runs/<unit>/` folder (§7, S3): state.json (commit point, S5), the pinned
 * workflow (S7), logs (C5), evidence and handoff.md (S9).
 */
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import type { UnitState, Workflow } from "@norn/schema";
import { assertValid } from "@norn/schema";
import { parse as parseYaml } from "yaml";
import { atomicCopyDir, atomicWrite, createExclusive, fileError, jsonLine, readJsonFile, readText, type ReadResult, validated } from "./fsx.ts";
import { evidenceDir, handoffPath, logPath, orphanedDir, pinnedWorkflowPath, statePath } from "./paths.ts";

// ---------------------------------------------------------------- state.json

export function readState(unitDir: string, root?: string): ReadResult<UnitState> {
  return readJsonFile("state", statePath(unitDir), root);
}

/** Validate and atomically write state.json. Callers write it last (S5). */
export function writeState(unitDir: string, state: UnitState): void {
  assertValid("state", state);
  atomicWrite(statePath(unitDir), jsonLine(state));
}

// ---------------------------------------------------------------- pinned workflow (S7)

export function sha256(text: string): string {
  return new Bun.CryptoHasher("sha256").update(text).digest("hex");
}

/** Parse workflow text (YAML or JSON — JSON is valid YAML) and validate it. */
export function parseWorkflowText(text: string, path: string, root?: string): ReadResult<Workflow> {
  let value: unknown;
  try {
    value = parseYaml(text);
  } catch (e) {
    return { ok: false, reason: "corrupt", error: fileError(path, [{ path: "", message: `YAML: ${(e as Error).message}` }], root) };
  }
  return validated("workflow", value, path, text, root);
}

export interface PinnedWorkflow {
  workflow: Workflow;
  /** sha256 of the file text (state.workflow_hash) */
  hash: string;
  source: string;
}

export function readPinnedWorkflow(unitDir: string, root?: string): ReadResult<PinnedWorkflow> {
  const path = pinnedWorkflowPath(unitDir);
  const raw = readText(path);
  if (raw === null) return { ok: false, reason: "missing" };
  const r = parseWorkflowText(raw, path, root);
  return r.ok ? { ok: true, raw, value: { workflow: r.value, hash: sha256(raw), source: raw } } : r;
}

/**
 * Copy the workflow text verbatim to `runs/<unit>/workflow.yaml` at unit start (S7).
 * Exclusive: an existing pin with identical text is fine (replay); a different one is
 * refused unless `replace` (the journaled `norn workflow --to` switch). Returns the hash.
 */
export function pinWorkflow(
  unitDir: string,
  source: string,
  opts: { replace?: boolean } = {},
): { ok: true; hash: string } | { ok: false; reason: "pinned"; hash: string } {
  const path = pinnedWorkflowPath(unitDir);
  const parsed = parseWorkflowText(source, path);
  if (!parsed.ok) throw new Error(`refusing to pin an invalid workflow: ${JSON.stringify(parsed.reason === "corrupt" ? parsed.error.errors : parsed.reason)}`);
  const hash = sha256(source);
  if (opts.replace) {
    atomicWrite(path, source);
    return { ok: true, hash };
  }
  if (createExclusive(path, source)) return { ok: true, hash };
  const existing = sha256(readText(path) ?? "");
  return existing === hash ? { ok: true, hash } : { ok: false, reason: "pinned", hash: existing };
}

// ---------------------------------------------------------------- logs and evidence (C5)

/** Write the full output of a run to `logs/<run_id>.log`; returns the unit-relative path. */
export function writeLog(unitDir: string, runId: string, text: string): string {
  atomicWrite(logPath(unitDir, runId), text);
  return `logs/${runId}.log`;
}

export function readLog(unitDir: string, runId: string): string | null {
  return readText(logPath(unitDir, runId));
}

/**
 * Create (if needed) `evidence/<run_id>/`; optionally copy a directory into it. The copy lands via
 * temp + rename (S1), so the evidence a `done` receipt names is never half-copied (P6).
 * Returns the unit-relative path.
 */
export function ensureEvidenceDir(unitDir: string, runId: string, copyFrom?: string): string {
  const dir = evidenceDir(unitDir, runId);
  if (copyFrom) atomicCopyDir(copyFrom, dir);
  else mkdirSync(dir, { recursive: true });
  return `evidence/${runId}`;
}

// ---------------------------------------------------------------- handoff.md (S9, O6)

export const HANDOFF_HEADER_BEGIN = "<!-- norn:header:begin — generated by norn from state.json; do not edit -->";
const HANDOFF_HEADER_END = "<!-- norn:header:end -->";
const HANDOFF_LOG_BEGIN = "<!-- norn:heartbeat:begin — written by norn; do not edit -->";
const HANDOFF_LOG_END = "<!-- norn:heartbeat:end -->";
const HANDOFF_SKELETON = "\n## Goal\n\n## Progress\n\n## Resume\n";

export interface Handoff {
  /** generated header content between the markers (no markers) */
  header: string;
  /** heartbeat lines (O6), oldest first */
  heartbeat: string[];
  /** agent/human-written part below the generated blocks, verbatim */
  body: string;
  raw: string;
}

function cutBlock(text: string, begin: string, end: string): { inner: string; rest: string } | null {
  const b = text.indexOf(begin);
  if (b !== 0) return null;
  const e = text.indexOf(end, b + begin.length);
  if (e < 0) return null;
  const inner = text.slice(b + begin.length, e).replace(/^\n/, "").replace(/\n$/, "");
  let rest = text.slice(e + end.length);
  if (rest.startsWith("\n")) rest = rest.slice(1);
  return { inner, rest };
}

/** Parse handoff.md. A file without norn blocks is all body (an agent's own text is never lost). */
export function parseHandoff(raw: string): Handoff {
  const head = cutBlock(raw, HANDOFF_HEADER_BEGIN, HANDOFF_HEADER_END);
  let rest = head ? head.rest : raw;
  let heartbeat: string[] = [];
  const log = cutBlock(rest, HANDOFF_LOG_BEGIN, HANDOFF_LOG_END);
  if (log) {
    heartbeat = log.inner.split("\n").filter((l) => l.trim() !== "");
    rest = log.rest;
  }
  return { header: head?.inner ?? "", heartbeat, body: rest, raw };
}

export function renderHandoff(h: Pick<Handoff, "header" | "heartbeat" | "body">): string {
  const parts = [HANDOFF_HEADER_BEGIN, h.header, HANDOFF_HEADER_END];
  if (h.heartbeat.length) parts.push(HANDOFF_LOG_BEGIN, ...h.heartbeat, HANDOFF_LOG_END);
  return `${parts.join("\n")}\n${h.body}`;
}

export function readHandoff(unitDir: string): Handoff | null {
  const raw = readText(handoffPath(unitDir));
  return raw === null ? null : parseHandoff(raw);
}

/**
 * Replace the generated header (rendered by the caller from state.json, S9) and keep
 * everything else verbatim. A new file gets the Goal / Progress / Resume skeleton.
 */
export function writeHandoffHeader(unitDir: string, header: string): Handoff {
  const cur = readHandoff(unitDir);
  const next = { header: header.replace(/\n+$/, ""), heartbeat: cur?.heartbeat ?? [], body: cur ? cur.body : HANDOFF_SKELETON };
  const raw = renderHandoff(next);
  atomicWrite(handoffPath(unitDir), raw);
  return { ...next, raw };
}

const REPEAT = /^(.*?)(?: \(×(\d+)\))?$/;

/** Append a heartbeat line (O6); a repeat of the last line collapses into "(×N)". Keeps the last `keep` lines. */
export function appendHandoffHeartbeat(unitDir: string, line: string, keep = 50): Handoff {
  const cur = readHandoff(unitDir) ?? { header: "", heartbeat: [], body: HANDOFF_SKELETON, raw: "" };
  const text = line.replace(/\s*\n\s*/g, " ").trim();
  const lines = [...cur.heartbeat];
  const last = lines.at(-1);
  const m = last ? REPEAT.exec(last) : null;
  if (m && m[1] === text) lines[lines.length - 1] = `${text} (×${Number(m[2] ?? 1) + 1})`;
  else lines.push(text);
  const next = { header: cur.header, heartbeat: lines.slice(-keep), body: cur.body };
  const raw = renderHandoff(next);
  atomicWrite(handoffPath(unitDir), raw);
  return { ...next, raw };
}

/** Replace the agent-written body (tests, `norn done --handoff` if it chooses to). Generated blocks are kept. */
export function writeHandoffBody(unitDir: string, body: string): Handoff {
  const cur = readHandoff(unitDir) ?? { header: "", heartbeat: [], body: "", raw: "" };
  const next = { header: cur.header, heartbeat: cur.heartbeat, body };
  const raw = renderHandoff(next);
  atomicWrite(handoffPath(unitDir), raw);
  return { ...next, raw };
}

// ---------------------------------------------------------------- orphaned runs (R2.3)

/**
 * R2.3: keep a copy of a runs/ file this checkout wrote but never got into the record, as
 * `runs/<unit>/orphaned/<holder>-<file name>` (a numeric suffix when taken). Receipt numbers under
 * `receipts/` are thereby freed and never reused or pushed. Returns the new path, or null when the
 * source file is gone.
 */
export function copyToOrphaned(unitDir: string, file: string, holder: string): string | null {
  const text = readText(file);
  if (text === null) return null;
  const name = `${holder}-${file.split("/").at(-1) ?? "file"}`.replace(/[\s/]/g, "_");
  for (let i = 0; i < 100; i++) {
    const dest = join(orphanedDir(unitDir), i ? name.replace(/(\.[^.]*)?$/, (ext) => `-${i}${ext}`) : name);
    const prev = readText(dest);
    if (prev === text) return dest;
    if (prev !== null) continue;
    mkdirSync(orphanedDir(unitDir), { recursive: true });
    atomicWrite(dest, text);
    return dest;
  }
  throw new Error(`too many orphaned copies of ${name} in ${orphanedDir(unitDir)}`);
}
