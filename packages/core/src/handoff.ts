/**
 * handoff.md rendering (S9, O6). The status block is rendered from state.json on every
 * commit and never parsed back; heartbeat lines are appended by the tool with repeats
 * collapsed ("(×3)"); everything else (Goal / Progress / Resume) belongs to agents and people.
 */
import type { UnitState, Workflow } from "@norn/schema";
import { nextCommand } from "./commands.ts";

export const STATUS_BEGIN = "<!-- norn:status — generated from state.json, do not edit -->";
export const STATUS_END = "<!-- /norn:status -->";
export const HEARTBEAT_BEGIN = "<!-- norn:heartbeat — generated by norn, do not edit -->";
export const HEARTBEAT_END = "<!-- /norn:heartbeat -->";

const SKELETON = ["## Goal", "", "## Progress", "", "## Resume", ""].join("\n");

export interface HeartbeatLine {
  /** ISO time */
  at: string;
  text: string;
}

/** The generated status block (S9): story, slice, step, attempt, counters, last outcome, next command. */
export function renderHandoffStatus(state: UnitState, opts: { workflow?: Workflow | null; next?: string | null } = {}): string {
  const key = state.slice ?? state.story;
  const max = opts.workflow?.counters ?? {};
  const counters = Object.keys({ ...max, ...state.counters })
    .sort()
    .map((c) => `${c} ${state.counters[c] ?? 0}${max[c] ? `/${max[c].max}` : ""}`);
  const status = state.park ? `${state.status} (${state.park.kind}: ${state.park.reason})` : state.status;
  const last = state.last_outcome ? `${state.last_outcome.step}.${state.last_outcome.outcome} (${state.last_outcome.source}, ${state.last_outcome.at})` : "none";
  const next = opts.next === undefined ? nextCommand(key, state) : opts.next;
  const lines = [
    STATUS_BEGIN,
    `- Story: ${state.story}${state.slice ? ` · Slice: ${state.slice}` : ""}`,
    `- Workflow: ${state.workflow} · Step: ${state.step} (attempt ${state.attempt})`,
    `- Status: ${status}`,
    `- Counters: ${counters.length ? counters.join(", ") : "none"}`,
    `- Last outcome: ${last}`,
    `- Next: ${next ? `\`${next}\`` : "nothing — done"}`,
    `- Updated: ${state.updated_at}`,
    STATUS_END,
  ];
  return lines.join("\n");
}

const LINE_RE = /^- (\S+) (.*?)(?: \(×(\d+)\))?$/;

/** Append a heartbeat line, collapsing a repeat of the last line into "(×n)" with the newest time (O6). */
export function collapseHeartbeat(lines: readonly string[], line: HeartbeatLine): string[] {
  const out = [...lines];
  const last = out.at(-1);
  const m = last ? LINE_RE.exec(last) : null;
  if (m && m[2] === line.text) {
    out[out.length - 1] = `- ${line.at} ${line.text} (×${Number(m[3] ?? 1) + 1})`;
    return out;
  }
  out.push(`- ${line.at} ${line.text}`);
  return out;
}

function between(doc: string, begin: string, end: string): { before: string; inner: string; after: string } | null {
  const i = doc.indexOf(begin);
  const j = i < 0 ? -1 : doc.indexOf(end, i + begin.length);
  if (i < 0 || j < 0) return null;
  return { before: doc.slice(0, i), inner: doc.slice(i + begin.length, j), after: doc.slice(j + end.length) };
}

/**
 * Next handoff.md text: replace the status block (or put it on top), append heartbeat lines
 * into the heartbeat block (created at the end), and keep every other line untouched.
 */
export function renderHandoff(existing: string | null, status: string, heartbeat: readonly HeartbeatLine[] = []): string {
  let doc = existing ?? `${status}\n\n${SKELETON}`;
  const s = between(doc, STATUS_BEGIN, STATUS_END);
  doc = s ? `${s.before}${status}${s.after}` : `${status}\n\n${doc.trimStart()}`;
  if (!heartbeat.length) return doc.endsWith("\n") ? doc : `${doc}\n`;
  const h = between(doc, HEARTBEAT_BEGIN, HEARTBEAT_END);
  let lines = h ? h.inner.split("\n").filter((l) => l.startsWith("- ")) : [];
  for (const l of heartbeat) lines = collapseHeartbeat(lines, l);
  const block = [HEARTBEAT_BEGIN, ...lines, HEARTBEAT_END].join("\n");
  doc = h ? `${h.before}${block}${h.after}` : `${doc.trimEnd()}\n\n## Heartbeat\n\n${block}\n`;
  return doc.endsWith("\n") ? doc : `${doc}\n`;
}
