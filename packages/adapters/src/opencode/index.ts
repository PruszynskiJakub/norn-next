/**
 * OpenCode agent adapter (`hooks` tier: it cannot block a turn end).
 * OpenCode has no hook config; norn installs a norn-owned plugin file
 * `<repo>/.opencode/plugins/norn.js` that forwards events to `<hookCommand> <arg>` with a JSON
 * payload on stdin (shape below, normalized by parseHookEvent).
 */
import { readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import type { AgentAdapter, AgentFactory, AgentLaunchRequest, HookAnswer, HookResponse, ToolCall } from "@norn/core";
import type { HookEventKind, HookFact } from "@norn/schema";
import { atomicWrite } from "@norn/store";
import * as shared from "../agent-hooks/index.ts";
import { portError } from "../exec.ts";

const { buildFact, field, isObject, launchEnv, readJsonFile, textOf } = shared;
const NAME = "opencode";
const PLUGIN_MARKER = "// norn-owned plugin";

/** Plugin event (`norn hook <arg>` argument) → kind. */
export const hookEvents = {
  "session.created": "session_start",
  "chat.message": "turn_start",
  "tool.execute.before": "tool_use",
  "tool.execute.after": "tool_use",
  "permission.asked": "permission_prompt",
  "session.idle": "turn_end",
  "session.deleted": "session_end",
} as const satisfies Record<string, HookEventKind>;

export const pluginPath = (repoRoot: string) => join(repoRoot, ".opencode", "plugins", "norn.js");

/** Plugin source. Payload on stdin: {hook_event_name, session_id, cwd, tool?, command?, message?}. */
function pluginSource(hookCommand: string, agent: string = NAME): string {
  return `${PLUGIN_MARKER} — generated by \`norn init\`; \`norn uninstall\` removes it. Do not edit.
const HOOK = ${JSON.stringify(hookCommand)};
const AGENT = ${JSON.stringify(agent)};
const send = (name, data) => {
  try {
    const proc = Bun.spawn(["sh", "-c", HOOK + " " + JSON.stringify(name) + " --agent " + AGENT], {
      stdin: new Blob([JSON.stringify({ hook_event_name: name, ...data })]),
      stdout: "ignore",
      stderr: "ignore",
    });
    return proc.exited;
  } catch {}
};
export const NornPlugin = async ({ directory }) => ({
  event: async ({ event }) => {
    const p = event.properties ?? {};
    const sid = p.sessionID ?? p.info?.id;
    if (event.type === "session.created" || event.type === "session.deleted" || event.type === "session.idle")
      await send(event.type, { session_id: sid, cwd: directory });
    else if (event.type === "permission.asked")
      await send(event.type, { session_id: sid, cwd: directory, message: p.title ?? p.permission, tool: p.type });
  },
  "chat.message": async (input) => send("chat.message", { session_id: input.sessionID, cwd: directory }),
  "tool.execute.before": async (input, output) =>
    send("tool.execute.before", { session_id: input.sessionID, cwd: directory, tool: input.tool, command: output?.args?.command }),
  "tool.execute.after": async (input) => send("tool.execute.after", { session_id: input.sessionID, cwd: directory, tool: input.tool }),
});
`;
}
// TODO: verify `chat.message` / `permission.asked` property names against the current OpenCode plugin types.

function readPlugin(repoRoot: string): string | null {
  try {
    return readFileSync(pluginPath(repoRoot), "utf8");
  } catch {
    return null;
  }
}

export function parseHookEvent(arg: string, payload: unknown, env: Record<string, string | undefined>, at: string): HookFact | null {
  const native = field(payload, "hook_event_name") ?? arg;
  if (!(native in hookEvents)) return null;
  return buildFact(
    {
      event: hookEvents[native as keyof typeof hookEvents],
      agent: NAME,
      native,
      payload,
      at,
      agent_session_id: field(payload, "session_id"),
      tool: field(payload, "tool"),
      command: field(payload, "command") ?? (native === "permission.asked" ? field(payload, "message") : undefined),
      message: field(payload, "message"),
    },
    env,
  );
}

/** OpenCode's plugin ignores output: no answer reaches it, so every one is allow. */
export const hookResponse = (_fact: HookFact, _answer: HookAnswer): HookResponse => ({ stdout: "", exit_code: 0 });

/** No answer can refuse a call, so none is read. */
export const toolCall = (_native: string, _payload: unknown): ToolCall | null => null;

/** Interactive `opencode --prompt "<prompt>"`; headless `opencode run "<prompt>"`; resume `--session <id>`. */
export function launchCommand(req: AgentLaunchRequest): { argv: string[]; env: Record<string, string> } {
  const argv = [req.config.command ?? "opencode"];
  if (req.headless) argv.push("run");
  if (req.model) argv.push("--model", req.model);
  if (req.resume) argv.push("--session", req.resume);
  argv.push(...(req.config.args ?? []));
  if (req.headless) argv.push(req.prompt);
  else argv.push("--prompt", req.prompt);
  return { argv, env: launchEnv(req) };
}

/**
 * OpenCode keeps sessions in its storage dir, not one transcript; this reads an
 * `opencode export <session>` JSON file: `{messages:[{info:{role}, parts:[{type:"text",text}]}]}`.
 * TODO: hooks carry no transcript path — the CLI must export the session first.
 */
export async function lastAssistantMessage(transcriptPath: string): Promise<string | null> {
  const doc = await readJsonFile(transcriptPath);
  const messages = isObject(doc) && Array.isArray(doc.messages) ? doc.messages : [];
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (!isObject(m) || !isObject(m.info) || m.info.role !== "assistant") continue;
    const t = textOf(m.parts).trim();
    if (t) return t;
  }
  return null;
}

/** OpenCode skills: `.opencode/skills`. TODO: confirm singular vs plural dir. */
export const skillDir = (repoRoot: string) => join(repoRoot, ".opencode", "skills");

export const opencodeAgent: AgentAdapter = {
  name: NAME,
  tier: "hooks",
  hookEvents,
  async installHooks(repoRoot, hookCommand, agent = NAME) {
    const path = pluginPath(repoRoot);
    const existing = readPlugin(repoRoot);
    if (existing !== null && !existing.startsWith(PLUGIN_MARKER)) {
      throw portError("not_norn_owned", `${path} exists and is not norn-owned`);
    }
    const src = pluginSource(hookCommand, agent);
    if (existing === src) return { changed: [] };
    atomicWrite(path, src);
    return { changed: [path] };
  },
  async uninstallHooks(repoRoot) {
    const existing = readPlugin(repoRoot);
    if (existing === null || !existing.startsWith(PLUGIN_MARKER)) return { changed: [] };
    rmSync(pluginPath(repoRoot));
    return { changed: [pluginPath(repoRoot)] };
  },
  async hooksInstalled(repoRoot) {
    return readPlugin(repoRoot)?.startsWith(PLUGIN_MARKER) ?? false;
  },
  parseHookEvent,
  hookResponse,
  toolCall,
  skillDir,
  launchCommand,
  lastAssistantMessage,
};

export const createAgent: AgentFactory = () => opencodeAgent;
