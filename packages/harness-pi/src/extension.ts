/**
 * The source of the pi extension norn installs. pi has no hook config of its own: an extension is
 * how anything outside it sees its events. This one runs `<hookCommand> <event>` with a JSON
 * payload on stdin and applies the hook command's stdout, the reply protocol `respond` renders:
 * - `{"block":true,"reason":…}` on `tool_call` refuses that call;
 * - `{"continue":…}` on `agent_before_settle` appends the text as a message and asks pi for one more run;
 * - `{"context":…}` on `session_start`, `session_compact` or `before_agent_start` reaches the model
 *   in the run under way (steered in), else goes with the next prompt.
 *
 * A settle pi will not continue (an error or aborted response is a hard exit) is never forwarded as
 * `agent_before_settle`, whose reply could ask for a continuation: its stop goes with
 * `agent_settled`, which nothing answers, so norn reads the turn as ended rather than refused.
 *
 * The extension is text the harness writes into a worktree; it runs inside pi, never in norn.
 */
import { RUN_ENV } from "@norn/plugin-api";
import { WRITE_TOOLS } from "./hooks.ts";

/** The first line of every extension norn writes: a file without it is a person's and is never touched. */
export const EXTENSION_MARKER = "// norn-owned pi extension";

/** How long the extension waits on the hook command; a hung hook must not hang pi. */
export const HOOK_TIMEOUT_MS = 120_000;

/** Why the extension refuses a write when the hook command failed, the same rule norn's own failure follows. */
export const FAILED_WRITE_REASON =
  "norn: this write was not checked against the unit's worktree, because norn's hook command failed. Try it again; if it keeps failing, tell the person.";

// String.raw keeps the body's backslashes as pi will read them; the body spells no `${`, so nothing in it is interpolated here
const BODY = String.raw`__MARKER__: generated by norn's pi harness, rewritten at each launch. Do not edit.
import { spawn } from "node:child_process";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HOOK = __HOOK__;
const WRITE_TOOLS = __WRITE_TOOLS__;
const RUN_ENV = __RUN_ENV__;
const TIMEOUT_MS = __TIMEOUT__;
const FAILED_WRITE = __FAILED_WRITE__;

export const commandFor = (name) => HOOK + " " + name;

// a failed hook is { ok: false }: the caller decides, as a guarded write is refused and anything else let through
function run(name, payload) {
  return new Promise((resolve) => {
    let out = "";
    let child;
    let settled = false;
    let timer;
    const done = (r) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(r);
    };
    timer = setTimeout(() => {
      try {
        if (child) child.kill("SIGKILL");
      } catch {}
      done({ ok: false });
    }, TIMEOUT_MS);
    try {
      child = spawn("sh", ["-c", commandFor(name)], { stdio: ["pipe", "pipe", "ignore"] });
    } catch {
      return done({ ok: false });
    }
    child.stdout.on("data", (d) => (out += d));
    child.on("error", () => done({ ok: false }));
    child.on("close", (code) => {
      if (code !== 0) return done({ ok: false });
      if (!out.trim()) return done({ ok: true, reply: {} });
      try {
        const v = JSON.parse(out);
        done(v && typeof v === "object" && !Array.isArray(v) ? { ok: true, reply: v } : { ok: false });
      } catch {
        done({ ok: false });
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify({ hook_event_name: name, ...payload }));
  });
}

const session = (ctx) => ({
  session_id: ctx.sessionManager.getSessionId(),
  transcript_path: ctx.sessionManager.getSessionFile(),
  cwd: ctx.cwd,
});

const textOf = (m) =>
  Array.isArray(m.content)
    ? m.content
        .filter((p) => p && p.type === "text")
        .map((p) => p.text)
        .join("\n")
        .trim()
    : typeof m.content === "string"
      ? m.content.trim()
      : "";

// the newest assistant message says how the run stopped; its text may be empty, so the words come from the newest that has some
function lastAssistant(ctx) {
  const branch = ctx.sessionManager.getBranch();
  let stop;
  for (let i = branch.length - 1; i >= 0; i--) {
    const m = branch[i] && branch[i].type === "message" ? branch[i].message : undefined;
    if (!m || m.role !== "assistant") continue;
    if (!stop) stop = { stop_reason: m.stopReason, error_message: m.errorMessage };
    const text = textOf(m);
    if (text) return { ...stop, last_assistant_message: text };
  }
  return stop || {};
}

const UNICODE_SPACES = /[\u00A0\u2000-\u200A\u202F\u205F\u3000]/g;

// the file pi's write and edit tools will touch, by their own rules (resolveToCwd): norn guards that path, never the text the model typed
function resolvedPath(input, cwd) {
  const raw = input && typeof input.path === "string" ? input.path : "";
  if (!raw || typeof cwd !== "string") return undefined;
  try {
    let p = raw.replace(UNICODE_SPACES, " ");
    if (p.startsWith("@")) p = p.slice(1);
    if (p === "~") p = homedir();
    else if (p.startsWith("~/")) p = join(homedir(), p.slice(2));
    else if (/^file:\/\//.test(p)) p = fileURLToPath(p);
    return resolve(cwd, p);
  } catch {
    return undefined;
  }
}

const running = (ctx) => {
  try {
    return typeof ctx.isIdle === "function" && !ctx.isIdle();
  } catch {
    return false;
  }
};

// a dialog's id is per opening, never per wording: the same title asked twice is two questions. The
// base keeps ids apart across a reload, which starts this module's count again
const PROMPT_BASE = Date.now().toString(36);
let prompts = 0;

export function wire(pi, send) {
  // context held for the next prompt, when no run was under way to steer it into
  let notes = [];
  // how the last settle ended, when pi would not continue it: agent_settled carries it
  let stopped;
  const forward = async (name, ctx, data) => {
    try {
      const r = await send(name, { ...session(ctx), ...data() });
      return r && r.ok && r.reply && typeof r.reply === "object" ? r : { ok: false };
    } catch {
      return { ok: false };
    }
  };
  const take = () => {
    const content = notes.join("\n\n");
    notes = [];
    return content;
  };
  const keep = (r, ctx) => {
    if (!r.ok || typeof r.reply.context !== "string" || !r.reply.context) return;
    if (running(ctx)) {
      try {
        pi.sendMessage({ customType: "norn", content: r.reply.context, display: false }, { deliverAs: "steer" });
        return;
      } catch {}
    }
    notes.push(r.reply.context);
  };

  pi.on("session_start", async (event, ctx) => {
    keep(await forward("session_start", ctx, () => ({ reason: event.reason })), ctx);
  });
  pi.on("session_compact", async (event, ctx) => {
    keep(await forward("session_compact", ctx, () => ({ reason: event.reason })), ctx);
  });
  pi.on("before_agent_start", async (event, ctx) => {
    const r = await forward("before_agent_start", ctx, () => ({ message_type: event.messageType, prompt: event.prompt }));
    // the run is about to start: what this prompt brings goes with it, never steered into the run before
    if (r.ok && typeof r.reply.context === "string" && r.reply.context) notes.push(r.reply.context);
    if (!notes.length) return;
    return { message: { customType: "norn", content: take(), display: false } };
  });
  pi.on("tool_call", async (event, ctx) => {
    const r = await forward("tool_call", ctx, () => {
      const path = WRITE_TOOLS.includes(event.toolName) ? resolvedPath(event.input, ctx.cwd) : undefined;
      return { tool_call_id: event.toolCallId, tool_name: event.toolName, tool_input: event.input, ...(path && { resolved_path: path }) };
    });
    if (!r.ok) return WRITE_TOOLS.includes(event.toolName) ? { block: true, reason: FAILED_WRITE } : undefined;
    if (r.reply.block === true) return { block: true, reason: typeof r.reply.reason === "string" && r.reply.reason ? r.reply.reason : "refused by norn" };
  });
  pi.on("tool_execution_end", async (event, ctx) => {
    await forward("tool_execution_end", ctx, () => ({ tool_call_id: event.toolCallId, tool_name: event.toolName, is_error: event.isError === true }));
  });
  pi.on("ui_prompt_start", async (event, ctx) => {
    const seq = PROMPT_BASE + "-" + ++prompts;
    await forward("ui_prompt_start", ctx, () => ({ kind: event.kind, title: event.title, prompt_seq: seq }));
  });
  pi.on("ui_prompt_end", async (_event, ctx) => {
    await forward("ui_prompt_end", ctx, () => ({}));
  });
  pi.on("agent_before_settle", async (event, ctx) => {
    const outcome = typeof event.outcome === "string" ? event.outcome : "completed";
    if (outcome !== "completed") {
      stopped = { outcome };
      return;
    }
    stopped = undefined;
    const r = await forward("agent_before_settle", ctx, () => ({ outcome, ...lastAssistant(ctx) }));
    if (!r.ok || typeof r.reply.continue !== "string" || !r.reply.continue) return;
    const entries = Array.isArray(event.entries) ? event.entries : [];
    // held context rides on the continuation, which is the next thing the model reads
    const held = notes.length ? [{ type: "custom_message", customType: "norn", content: take(), display: false }] : [];
    return { entries: [...entries, ...held, { type: "custom_message", customType: "norn", content: r.reply.continue, display: true }], continue: true };
  });
  pi.on("agent_settled", async (event, ctx) => {
    const stop = stopped;
    stopped = undefined;
    await forward("agent_settled", ctx, () => ({ aborted: event.aborted === true, ...(stop && { outcome: stop.outcome, ...lastAssistant(ctx) }) }));
  });
  pi.on("session_shutdown", async (event, ctx) => {
    await forward("session_shutdown", ctx, () => ({ reason: event.reason }));
  });
}

// only a session norn launched carries its unit and run in the env; a person's own pi here is left alone
export default function (pi) {
  if (RUN_ENV.every((k) => Boolean(process.env[k]))) wire(pi, run);
}
`;

const SLOTS: Record<string, (hookCommand: string) => string> = {
  __MARKER__: () => EXTENSION_MARKER,
  __HOOK__: (hookCommand) => JSON.stringify(hookCommand),
  __WRITE_TOOLS__: () => JSON.stringify(WRITE_TOOLS),
  __RUN_ENV__: () => JSON.stringify([RUN_ENV.unit, RUN_ENV.run]),
  __TIMEOUT__: () => String(HOOK_TIMEOUT_MS),
  __FAILED_WRITE__: () => JSON.stringify(FAILED_WRITE_REASON),
};

/** The extension's text for one hook command. Pure, so the same command always yields the same bytes. */
export function extensionSource(hookCommand: string): string {
  // a replacer function, never a replacement string: a `$&` in the hook command must stay as typed
  return BODY.replace(/__[A-Z_]+__/g, (slot) => SLOTS[slot]?.(hookCommand) ?? slot);
}
